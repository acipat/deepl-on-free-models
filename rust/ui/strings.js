  let activeLanguage = "en";

  /** Look up a key in the active table, falling back to English, then the key. */
  function translate(key) {
    const table = window.OFM_STRINGS[activeLanguage];
    if (table && Object.prototype.hasOwnProperty.call(table, key) && table[key]) {
      return table[key];
    }
    const english = window.OFM_STRINGS.en;
    if (english && Object.prototype.hasOwnProperty.call(english, key) && english[key]) {
      return english[key];
    }
    return key;
  }

  window.OFM_TRANSLATE = translate;
  window.t = translate;

  /** Switch language after a table has been provided by the shell. */
  window.OFM_SET_LANGUAGE = function (code) {
    activeLanguage = code && window.OFM_STRINGS[code] ? code : "en";
    document.documentElement.lang = activeLanguage;
    if (window.OFM_UI && typeof window.OFM_UI.relocalize === "function") {
      window.OFM_UI.relocalize();
    }
  };

  /** Register (or replace) a translation table and optionally activate it. */
  window.OFM_APPLY_STRINGS = function (code, table, activate) {
    if (!code || !table) return;
    window.OFM_STRINGS[code] = Object.assign({}, window.OFM_STRINGS[code] || {}, table);
    if (activate !== false) window.OFM_SET_LANGUAGE(code);
  };
